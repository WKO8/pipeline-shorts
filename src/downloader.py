from __future__ import annotations

import json
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional

from .config import AppConfig
from src.utils import ensure_dir, read_json, run_cmd, write_json, which

LOGGER = logging.getLogger(__name__)


@dataclass(slots=True)
class DownloadResult:
    """
    Artifacts generated by the download stage.
    """

    video_path: Path
    audio_path: Path
    info_json_path: Path
    title: str
    uploader: Optional[str]
    duration: Optional[float]
    webpage_url: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "video_path": str(self.video_path),
            "audio_path": str(self.audio_path),
            "info_json_path": str(self.info_json_path),
            "title": self.title,
            "uploader": self.uploader,
            "duration": self.duration,
            "webpage_url": self.webpage_url,
        }


class YouTubeDownloader:
    """
    Download YouTube video with best quality and extract separate audio file.

    Pipeline behavior:
    1) Fetch metadata JSON (title, duration, etc.)
    2) Download merged MP4 (bestvideo+bestaudio fallback configurable)
    3) Extract clean WAV audio from the MP4 for Whisper transcription
       (can be switched to MP3 by changing extract_audio_format)
    """

    def __init__(
        self,
        config: AppConfig,
        extract_audio_format: str = "wav",
        audio_sample_rate: int = 16000,
        audio_channels: int = 1,
    ) -> None:
        self.config = config
        self.extract_audio_format = extract_audio_format.lower().strip()
        self.audio_sample_rate = audio_sample_rate
        self.audio_channels = audio_channels

        if self.extract_audio_format not in {"wav", "mp3"}:
            raise ValueError("extract_audio_format must be either 'wav' or 'mp3'")

    def _cookie_args(self) -> list[str]:
        """Return yt-dlp cookie flags based on config, or [] if none are set."""
        if self.config.ytdlp_cookies_from_browser:
            return ["--cookies-from-browser", self.config.ytdlp_cookies_from_browser]
        if self.config.ytdlp_cookies_file:
            return ["--cookies", self.config.ytdlp_cookies_file]
        return []

    def _js_runtime_args(self) -> list[str]:
        """Return --js-runtimes flag with path, auto-detecting Node if available."""
        import shutil

        runtime = self.config.ytdlp_js_runtime
        if not runtime:
            node_path = shutil.which("node")
            if node_path:
                return ["--js-runtimes", f"node:{node_path}"]
            return []

        # If no explicit path, auto-detect node
        if runtime.lower() == "node" and ":" not in runtime:
            node_path = shutil.which("node")
            if not node_path:
                home = Path.home()
                for candidate in sorted(
                    list((home / ".nvm" / "versions" / "node").glob("*/bin/node"))
                    + [home / ".local" / "share" / "pnpm" / "bin" / "node"],
                    reverse=True,
                ):
                    if candidate.exists():
                        node_path = str(candidate)
                        break
            if node_path:
                runtime = f"node:{node_path}"

        return ["--js-runtimes", runtime]

    def _remote_components_args(self) -> list[str]:
        """Return yt-dlp remote component solver selection."""
        return ["--remote-components", "ejs:github"]

    def _extractor_args(self) -> list[str]:
        """Return --extractor-args youtube:... flag if configured."""
        if not self.config.ytdlp_extractor_args:
            return []
        return ["--extractor-args", f"youtube:{self.config.ytdlp_extractor_args}"]


    def _find_existing_video(self, video_id: str) -> Optional[Path]:
        """
        Check if a video with the given ID already exists in the downloads directory.
        Looks for {id}.info.json and verifies the associated video file.
        """
        if not video_id:
            return None
            
        # 1. Direct check: {video_id}.info.json
        registry_path = self.config.downloads_dir / f"{video_id}.info.json"
        if registry_path.exists():
            try:
                meta = json.loads(registry_path.read_text(encoding='utf-8'))
                v_path = Path(meta.get('_last_known_path', ''))
                if v_path and v_path.exists():
                    return v_path
            except Exception:
                pass

        # 2. Heuristic check: Search all .info.json files in downloads folder
        for info_path in self.config.downloads_dir.glob("*.info.json"):
            try:
                meta = json.loads(info_path.read_text(encoding='utf-8'))
                if meta.get('id') == video_id:
                    v_path = Path(meta.get('_last_known_path', ''))
                    if v_path and v_path.exists():
                        return v_path
                    v_path = info_path.with_suffix('.mp4')
                    if v_path.exists():
                        return v_path
            except Exception:
                continue
                
        return None

    def download(self, url: str, slug: str) -> DownloadResult:
        """
        Execute the full download flow and return output paths + metadata.
        Checks if the video was already downloaded to save bandwidth and time.
        """
        if not url or not url.strip():
            raise ValueError("YouTube URL is required")
        if not slug or not slug.strip():
            raise ValueError("slug is required")

        ensure_dir(self.config.downloads_dir)
        ensure_dir(self.config.audio_dir)
        ensure_dir(self.config.temp_dir)

        # 1. Fetch metadata first (fast)
        info_json_path = self._fetch_info_json(url=url, slug=slug)
        metadata = self._load_metadata(info_json_path)
        video_id = metadata.get('id')

        # 2. Check for existing download
        existing_video = self._find_existing_video(video_id)
        
        if existing_video:
            LOGGER.info("Existing video found for ID %s: %s", video_id, existing_video.name)
            mp4_path = existing_video
        else:
            # 3. Download if not found
            mp4_path = self._download_video_mp4(url=url, slug=slug)
            # Update metadata with the actual path and save to registry
            metadata['_last_known_path'] = str(mp4_path.resolve())
            registry_path = self.config.downloads_dir / f"{video_id}.info.json"
            registry_path.write_text(json.dumps(metadata), encoding='utf-8')

        # 4. Extract audio
        audio_path = self._extract_audio(input_video=mp4_path, slug=slug)

        result = DownloadResult(
            video_path=mp4_path,
            audio_path=audio_path,
            info_json_path=info_json_path,
            title=(metadata.get("title") or slug),
            uploader=metadata.get("uploader"),
            duration=self._safe_float(metadata.get("duration")),
            webpage_url=(metadata.get("webpage_url") or url),
        )
        LOGGER.info("Download stage complete: %s", result.to_dict())
        return result

    def _fetch_info_json(self, url: str, slug: str) -> Path:
        info_json_path = self.config.temp_dir / f"{slug}.info.json"

        # Use --dump-single-json to retrieve metadata without downloading media.
        yt_dlp_cmd = which("yt-dlp") or "yt-dlp"
        
        cmd = [
            yt_dlp_cmd,
            "--no-warnings",
            "--dump-single-json",
            "--no-playlist",
            *self._cookie_args(),
            *self._js_runtime_args(),
            *self._remote_components_args(),
            *self._extractor_args(),
            url,
        ]
        result = run_cmd(cmd, check=True)
        info_json_path.write_text(result.stdout, encoding="utf-8")
        return info_json_path

    def _load_metadata(self, info_json_path: Path) -> dict[str, Any]:
        try:
            return json.loads(info_json_path.read_text(encoding="utf-8"))
        except Exception as exc:  # noqa: BLE001
            raise RuntimeError(f"Failed to parse yt-dlp metadata JSON: {exc}") from exc

    def _download_video_mp4(self, url: str, slug: str) -> Path:
        output_template = self.config.downloads_dir / f"{slug}.%(ext)s"

        # Force MP4 remux when possible.
        # format fallback controlled by config.ytdlp_format
        yt_dlp_cmd = which("yt-dlp") or "yt-dlp"
        
        cmd = [
            yt_dlp_cmd,
            "--no-warnings",
            "--no-playlist",
            "--force-overwrites",
            "-f",
            self.config.ytdlp_format,
            "--merge-output-format",
            "mp4",
            "--concurrent-fragments",
            str(max(1, getattr(self.config, "ytdlp_concurrent_fragments", 4))),
            "--buffer-size",
            str(getattr(self.config, "ytdlp_buffersize", "16M")),
            "-o",
            str(output_template),
            *self._cookie_args(),
            *self._js_runtime_args(),
            *self._remote_components_args(),
            *self._extractor_args(),
            url,
        ]
        run_cmd(cmd, check=True)

        mp4_path = self.config.downloads_dir / f"{slug}.mp4"
        if not mp4_path.exists():
            # In rare cases yt-dlp may keep a different extension.
            # Search by slug stem and prefer mp4-compatible formats.
            candidates = sorted(self.config.downloads_dir.glob(f"{slug}.*"))
            if not candidates:
                raise RuntimeError(
                    "Video download completed but output file was not found"
                )
            # Best-effort fallback: pick latest candidate.
            mp4_path = candidates[-1]

        return mp4_path

    def _extract_audio(self, input_video: Path, slug: str) -> Path:
        ext = self.extract_audio_format
        output_audio = self.config.audio_dir / f"{slug}.{ext}"

        if ext == "wav":
            cmd = [
                "ffmpeg",
                "-y",
                "-i",
                str(input_video),
                "-vn",
                "-ac",
                str(self.audio_channels),
                "-ar",
                str(self.audio_sample_rate),
                "-c:a",
                "pcm_s16le",
                str(output_audio),
            ]
        else:
            # mp3
            cmd = [
                "ffmpeg",
                "-y",
                "-i",
                str(input_video),
                "-vn",
                "-ac",
                str(self.audio_channels),
                "-ar",
                str(self.audio_sample_rate),
                "-c:a",
                "libmp3lame",
                "-b:a",
                "192k",
                str(output_audio),
            ]

        run_cmd(cmd, check=True)
        if not output_audio.exists():
            raise RuntimeError(f"Audio extraction failed: {output_audio} not found")
        return output_audio

    @staticmethod
    def _safe_float(value: Any) -> Optional[float]:
        if value is None:
            return None
        try:
            return float(value)
        except (TypeError, ValueError):
            return None
